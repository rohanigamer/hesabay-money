export const setLanguage = async (lang) => {
  if (translations[lang]) {
    currentLanguage = lang;
    i18n.locale = lang;
    I18n.locale = lang;
    I18n.translations = translations;
    await Storage.setLanguage(lang);
  }
};

export const getLanguage = () => {
  return currentLanguage || i18n.locale;
};

